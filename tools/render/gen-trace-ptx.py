#!/usr/bin/env python3
"""Turns the PTX that NVRTC made from mod/src/hqrender/cuda/trace.cu into mod/src/hqrender/java/dev/t3craft/tools/hqrender/gpu/TracePtx.java.

    # 1. a render job on the PC compiles the kernel with NVRTC and keeps the PTX in its outbox:
    tools/render/submit.sh --layout hybrid-ringcampus --projects 4 --only hub --gpu-compare --gpu-nvrtc
    # 2. embed it (the runtime then needs only the CUDA driver, no NVRTC):
    python3 tools/render/gen-trace-ptx.py ~/.cache/t3craft-render/outbox/<job>/trace.ptx

Standard library only. The PTX is split in constants of at most 32000 characters (the class file limit per string constant is 65535 bytes).
"""
import hashlib
import os
import sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, "..", ".."))
src = os.path.join(root, "mod/src/hqrender/cuda/trace.cu")
dst = os.path.join(root, "mod/src/hqrender/java/dev/t3craft/tools/hqrender/gpu/TracePtx.java")
ptx = open(sys.argv[1], encoding="ascii").read()
# comments and blank lines only cost size
lines = [l.rstrip() for l in ptx.split("\n") if l.strip() and not l.lstrip().startswith("//")]
ptx = "\n".join(lines) + "\n"
sha = hashlib.sha256(open(src, "rb").read()).hexdigest()

parts = [ptx[i:i + 32000] for i in range(0, len(ptx), 32000)]


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'


out = []
out.append("package dev.t3craft.tools.hqrender.gpu;\n")
out.append("/**")
out.append(" * GENERATED by tools/render/gen-trace-ptx.py from NVRTC's PTX for mod/src/hqrender/cuda/trace.cu. Do not edit; change trace.cu,")
out.append(" * run a render job with {@code --gpu-nvrtc} on the render PC and generate this class again.")
out.append(" */")
out.append("final class TracePtx {")
out.append("\t/** sha256 of the trace.cu this PTX was made from. */")
out.append('\tstatic final String SOURCE_SHA256 = "%s";' % sha)
out.append("")
out.append("\tprivate TracePtx() {")
out.append("\t}")
out.append("")
for i, p in enumerate(parts):
    out.append("\tprivate static final String P%d = %s;" % (i, lit(p)))
out.append("")
out.append("\tstatic String text() {")
out.append("\t\treturn String.join(\"\", %s);" % ", ".join("P%d" % i for i in range(len(parts))))
out.append("\t}")
out.append("}")
open(dst, "w", encoding="ascii").write("\n".join(out) + "\n")
print("wrote %s: %d chars of PTX in %d parts, trace.cu sha256 %s" % (dst, len(ptx), len(parts), sha[:12]))
